#!/usr/bin/env python3
"""Aggregate fit_benchmark JSON files into Markdown and LaTeX tables."""

from __future__ import annotations

import argparse
import json
import statistics
from collections import defaultdict
from pathlib import Path


STRATEGY_LABELS = {
    "optuna": "Optuna (TPE)",
    "optuna_cmaes": "Optuna (CMA-ES)",
    "optuna_gp": "Optuna (GP-BO)",
    "optuna_qmc": "Optuna (QMC)",
    "optuna_random": "Random",
    "differential_evolution": "Diff. evolution",
    "dual_annealing": "Dual annealing",
    "lbfgsb": "L-BFGS-B only",
    "staged": "Staged",
    "staged_optuna": "Staged-Optuna",
    "staged_cmaes": "Staged-CMA-ES",
}


def _load_rows(bench_dir: Path) -> list[dict]:
    rows: list[dict] = []
    for path in sorted(bench_dir.glob("*.json")):
        target = path.stem
        for entry in json.loads(path.read_text()):
            rows.append({"target": target, **entry})
    if not rows:
        raise FileNotFoundError(f"no benchmark JSON under {bench_dir}")
    return rows


def _aggregate(rows: list[dict]) -> list[dict]:
    by_strategy: dict[str, list[dict]] = defaultdict(list)
    for row in rows:
        by_strategy[row["strategy"]].append(row)
    out: list[dict] = []
    for strategy in sorted(by_strategy, key=lambda s: STRATEGY_LABELS.get(s, s)):
        group = by_strategy[strategy]
        out.append(
            {
                "strategy": strategy,
                "label": STRATEGY_LABELS.get(strategy, strategy),
                "n_targets": len(group),
                "mean_weighted_error": statistics.mean(r["weighted_error"] for r in group),
                "median_weighted_error": statistics.median(
                    r["weighted_error"] for r in group
                ),
                "mean_rmse_log": statistics.mean(r["rmse_log"] for r in group),
                "mean_fit_wall_s": statistics.mean(r["fit_wall_s"] for r in group),
                "mean_n_evals": statistics.mean(r["n_evals"] for r in group),
            }
        )
    return sorted(out, key=lambda r: r["mean_weighted_error"])


def _markdown(agg: list[dict], *, iterations: int | None) -> str:
    lines = ["# Fit strategy benchmark (aggregated)", ""]
    if iterations is not None:
        lines.append(f"Optuna trial budget: **{iterations}** per global-search strategy.")
        lines.append("")
    lines.extend(
        [
            "| strategy | mean err. | median err. | mean log-RMSE | mean wall (s) | mean evals |",
            "|----------|----------:|------------:|--------------:|--------------:|-----------:|",
        ]
    )
    for row in agg:
        lines.append(
            f"| {row['label']} "
            f"| {row['mean_weighted_error']:.4f} "
            f"| {row['median_weighted_error']:.4f} "
            f"| {row['mean_rmse_log']:.4f} "
            f"| {row['mean_fit_wall_s']:.1f} "
            f"| {row['mean_n_evals']:.0f} |"
        )
    lines.append("")
    return "\n".join(lines)


def _latex(agg: list[dict], *, iterations: int | None, label: str) -> str:
    iter_note = f"{iterations} Optuna trials" if iterations else "configured trial budget"
    lines = [
        "% Auto-generated by scripts/summarize_fit_benchmark.py",
        "\\begin{table}[!t]",
        f"\\caption{{DC fit strategy comparison on custom $I_d$-$V_g$ targets ({iter_note}; mean over {agg[0]['n_targets']} cases).}}",
        f"\\label{{{label}}}",
        "\\centering",
        "\\footnotesize",
        "\\begin{tabular}{@{}lrrrr@{}}",
        "\\toprule",
        "Strategy & Mean err. & Median err. & Mean log-RMSE & Mean wall (s) \\\\",
        "\\midrule",
    ]
    for row in agg:
        lines.append(
            f"{row['label']} & "
            f"{row['mean_weighted_error']:.3f} & "
            f"{row['median_weighted_error']:.3f} & "
            f"{row['mean_rmse_log']:.3f} & "
            f"{row['mean_fit_wall_s']:.0f} \\\\"
        )
    lines.extend(["\\bottomrule", "\\end{tabular}", "\\end{table}", ""])
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--bench-dir",
        type=Path,
        required=True,
        help="Path to results/<lane>/fit_benchmark/acm5",
    )
    parser.add_argument("--iterations", type=int, default=None)
    parser.add_argument("--latex-out", type=Path, default=None)
    parser.add_argument("--latex-label", default="tab:strategy_bench")
    args = parser.parse_args()

    rows = _load_rows(args.bench_dir)
    agg = _aggregate(rows)
    md = _markdown(agg, iterations=args.iterations)
    print(md)
    if args.latex_out is not None:
        args.latex_out.parent.mkdir(parents=True, exist_ok=True)
        args.latex_out.write_text(
            _latex(agg, iterations=args.iterations, label=args.latex_label)
        )
        print(f"Wrote {args.latex_out}")


if __name__ == "__main__":
    main()
